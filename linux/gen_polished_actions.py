"""Generate verified normal-3.2.3 Bag observations; no ROM bytes or guessed offsets.
Input: official polishedcrystal-3.2.3.sym release asset. App-owned fields are
cross-checked against Gen2Reader.kt; ROM identity comes from the app's table.
"""
from pathlib import Path
import argparse, hashlib, re
p=argparse.ArgumentParser();p.add_argument('symbols',type=Path);p.add_argument('--check',action='store_true');a=p.parse_args()
raw=a.symbols.read_bytes()
digest=hashlib.sha256(raw).hexdigest()
if digest!='be1ca87ad487ade20701ed71fcae4e99bf16b908af727b84575c862b73ea2955':raise SystemExit('Wrong release symbols; review new versions explicitly')
symbols={n:(int(b,16)<<16)|int(v,16) for b,v,n in re.findall(r'^([0-9a-fA-F]+):([0-9a-fA-F]+) (\S+)$',raw.decode(),re.M)}
base=Path(__file__).resolve().parents[1]/'app/src/main/kotlin/com/pokedaisy/app/companion/data'
reader=(base/'Gen2Reader.kt').read_text().split('val GEN2_POLISHED_CRYSTAL = GEN2_CRYSTAL.copy(',1)[1].split('\n)',1)[0]
app={k:(int(b)<<16)|int(v,16) for k,b,v in re.findall(r'(\w+) = wramx\((\d+), (0x[0-9A-Fa-f]+)\)',reader)}
app.update({k:int(v,16) for k,v in re.findall(r'(\w+) = (0x[0-9A-Fa-f]+)L',reader)})
for field,sym in [('battleMode','wBattleMode'),('menuCursor','wMenuCursorY')]:
 if app[field]!=symbols[sym]:raise SystemExit('App / release observation mismatch: '+field)
ids=(base/'Gen2PolishedCrystalGen.kt').read_text()
sha=re.search(r'"([0-9a-f]{40})" to intArrayOf\([^\n]+// polishedcrystal-3\.2\.3\s*$',ids,re.M)
if not sha:raise SystemExit('App ROM identity changed')
fields={'STATE':'wStateFlags','SCRIPT':'wScriptMode','MAP':'wMapStatus','BATTLE':'wBattleMode','LIST':'wMenuItemsList','POINTER':'wMenuDataPointer','CURSOR':'wMenuCursorY','POCKET':'wCurPocket','SCROLL':'wMenuScrollPosition','ITEM':'wCurItem'}
out=['/* Generated by gen_polished_actions.py. GPL-3.0. No ROM bytes. */','/* Official v3.2.3 symbols SHA256 '+digest+' */','#ifndef PD_POLISHED_ACTION_DATA_H','#define PD_POLISHED_ACTION_DATA_H','#define PD_PC_ACTION_SHA "'+sha[1]+'"']
for key,sym in fields.items():out.append('#define PD_PC_'+key+' '+hex(symbols[sym])+'u /* '+sym+' */')
out.append('#define PD_PC_START_MENU '+hex(symbols['StartMenu.MenuData']&65535)+'u')
pockets=['Items','Medicine','Balls','Berries','KeyItems']
out.append('static const unsigned pd_pc_pack_menus[]={'+','.join(hex(symbols[x+'PocketMenuDataHeader.MenuData2']&65535) for x in pockets)+'};')
out.append('static const unsigned pd_pc_item_submenus[]={'+','.join(hex(symbols[x+'.MenuData2']&65535) for x in ['MenuDataHeader_UseGiveToss','MenuDataHeader_GiveToss','MenuDataHeader_Use'])+'};')
out.append('static const struct {unsigned addr, max, pocket, menu;} pd_pc_item_pockets[]={')
# Game pocket enum order (item_data_constants.asm), not a memory-address table.
for field,cap,pocket,menu,sym in [('numItems','itemsMax',0,0,'wNumItems'),('numMedicine','medicineMax',1,1,'wNumMedicine'),('numBalls','ballsMax',2,2,'wNumBalls'),('numBerries','berriesMax',4,3,'wNumBerries')]:
 if app[field]!=symbols[sym]:raise SystemExit('App / symbol bag mismatch: '+field)
 limit=re.search(r'\b'+cap+r' = (\d+)',reader)
 if not limit:raise SystemExit('Missing bag capacity: '+cap)
 out.append('{'+','.join([hex(app[field]),limit[1],str(pocket),str(menu)])+'},')
out.append('};')
out+=['#endif',''];text='\n'.join(out);dest=Path(__file__).with_name('polished_action_data.h')
if a.check:
 if not dest.exists() or dest.read_text()!=text:raise SystemExit('Regenerate polished_action_data.h')
else:dest.write_text(text)
