#!/usr/bin/env python3
"""Generates companion/data/save/SpeciesDexGen.kt - each internal species index's National and
Hoenn Dex numbers, the trade evolutions and the few item ids the trade rules name - from a
pokeemerald checkout ($DECOMPS/pokeemerald). Every Gen 3 game shares them (Treecko = species 277
= National 252; the evolution and item tables are the same in R/S/E/FR/LG), and a save on its own
has no ROM to read them from: the save editor's trades (National Dex / Hoenn Dex membership,
Pokédex flags, evolving on arrival) need them.

Inputs:
  include/constants/species.h   #define SPECIES_X n
  include/constants/pokedex.h   the NATIONAL_DEX_* / HOENN_DEX_* enums, HOENN_DEX_COUNT
  src/pokemon.c                 gSpeciesToNationalPokedexNum / gSpeciesToHoennPokedexNum
  include/constants/items.h     the ITEM_* enum, FIRST_MAIL_INDEX
  src/data/pokemon/evolution.h  EVO_TRADE / EVO_TRADE_ITEM entries

Usage: scripts/gen_species_dex.py [path/to/pokeemerald]
"""
import os
import re
import sys

from decomps import decomp

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else decomp("pokeemerald")
OUT = os.path.join(HERE, "../app/src/main/kotlin/com/pokedaisy/app/companion/data/save/SpeciesDexGen.kt")


def read(rel):
    with open(os.path.join(SRC, rel)) as f:
        return f.read()


def enum_values(text, prefix):
    """The members of the enum whose first member is <prefix>NONE, numbered from 0."""
    text = re.sub(r"//[^\n]*|/\*.*?\*/", "", text, flags=re.S)   # comments name members too
    start = text.index(prefix + "NONE")
    body = text[start:text.index("}", start)]
    names = re.findall(r"\b(" + prefix + r"\w+)", body)
    return {n: i for i, n in enumerate(names)}


def main():
    species = {m.group(1): int(m.group(2), 0)
               for m in re.finditer(r"#define (SPECIES_\w+)\s+(\d+|0x[0-9A-Fa-f]+)\b", read("include/constants/species.h"))}
    dex_h = read("include/constants/pokedex.h")
    national = enum_values(dex_h, "NATIONAL_DEX_")
    hoenn = enum_values(dex_h, "HOENN_DEX_")
    hoenn_count = hoenn["HOENN_DEX_DEOXYS"]
    assert re.search(r"#define HOENN_DEX_COUNT\s+HOENN_DEX_DEOXYS", dex_h), "HOENN_DEX_COUNT moved"

    pokemon_c = read("src/pokemon.c")
    count = species["SPECIES_EGG"]   # NUM_SPECIES
    nat = [0] * count
    hoe = [0] * count
    for m in re.finditer(r"^\s*SPECIES_TO_NATIONAL\((\w+)\)", pokemon_c, re.M):
        nat[species["SPECIES_" + m.group(1)]] = national["NATIONAL_DEX_" + m.group(1)]
    for m in re.finditer(r"^\s*SPECIES_TO_HOENN\((\w+)\)", pokemon_c, re.M):
        hoe[species["SPECIES_" + m.group(1)]] = hoenn["HOENN_DEX_" + m.group(1)]
    assert nat[species["SPECIES_TREECKO"]] == 252 and nat[species["SPECIES_CHIMECHO"]] == 358
    assert hoe[species["SPECIES_TREECKO"]] == 1 and nat[species["SPECIES_MEW"]] == 151

    items = enum_values(read("include/constants/items.h"), "ITEM_")
    first_mail = items["ITEM_ORANGE_MAIL"]
    last_mail = items["ITEM_RETRO_MAIL"]
    assert last_mail - first_mail == 11, "the mail items aren't 12 in a row any more"
    trade_evos = []
    evo_h = read("src/data/pokemon/evolution.h")
    for m in re.finditer(r"\[SPECIES_(\w+)\]\s*=\s*\{(.*?\})\}", evo_h, re.S):
        for e in re.finditer(r"\{(EVO_TRADE(?:_ITEM)?),\s*(\w+),\s*SPECIES_(\w+)\}", m.group(2)):
            item = 0 if e.group(1) == "EVO_TRADE" else items[e.group(2)]
            trade_evos.append((species["SPECIES_" + m.group(1)], item, species["SPECIES_" + e.group(3)], m.group(1), e.group(3)))
    assert len(trade_evos) == 12, trade_evos
    assert items["ITEM_KINGS_ROCK"] == 187 and items["ITEM_EVERSTONE"] == 195 and first_mail == 121

    def rows(values):
        return "\n".join("    " + ", ".join(str(v) for v in values[i:i + 20]) + "," for i in range(0, len(values), 20))

    with open(OUT, "w") as f:
        f.write(f"""package com.pokedaisy.app.companion.data.save

// GENERATED by scripts/gen_species_dex.py from pokeemerald (gSpeciesToNationalPokedexNum /
// gSpeciesToHoennPokedexNum) - do not hand-edit. Shared by every Gen 3 game, keyed by the
// internal species index (Treecko = 277). The unused 252-276 (OLD_UNOWN_*) get the game's placeholder
// numbers past 386; index 0 is 0.

/** National Dex number per internal species index, 0..{count - 1}. */
internal val speciesNationalDex: IntArray = intArrayOf(
{rows(nat)}
)

/** Hoenn Dex number per internal species index (non-Hoenn species are numbered past [HOENN_DEX_COUNT]). */
internal val speciesHoennDex: IntArray = intArrayOf(
{rows(hoe)}
)

/** The Hoenn Dex's last number (Deoxys): IsSpeciesInHoennDex is "<= this". */
internal const val HOENN_DEX_COUNT = {hoenn_count}

internal const val SPECIES_MEW = {species["SPECIES_MEW"]}
internal const val SPECIES_DEOXYS = {species["SPECIES_DEOXYS"]}
internal const val SPECIES_UNOWN = {species["SPECIES_UNOWN"]}
internal const val SPECIES_SPINDA = {species["SPECIES_SPINDA"]}
const val SPECIES_EGG = {species["SPECIES_EGG"]}
internal const val ITEM_EVERSTONE = {items["ITEM_EVERSTONE"]}
internal const val ITEM_ENIGMA_BERRY = {items["ITEM_ENIGMA_BERRY"]}
/** IS_ITEM_MAIL: ORANGE MAIL .. RETRO MAIL. */
internal val MAIL_ITEMS = {first_mail}..{last_mail}

/** gEvolutionTable's trade evolutions: species, the item it must hold (0 = none; used up), what it becomes. */
class TradeEvolution(val species: Int, val item: Int, val into: Int)

internal val tradeEvolutions: List<TradeEvolution> = listOf(
{chr(10).join(f"    TradeEvolution({a}, {b}, {c}), // {n} -> {t}" for a, b, c, n, t in trade_evos)}
)
""")
    print(f"wrote {OUT}: {count} species")


if __name__ == "__main__":
    main()
